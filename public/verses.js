赌胜马蹄下，由来轻七尺
青山朝别暮还见，嘶马出门思旧乡
月照城头乌半飞，霜凄万树风入衣
霜皮溜雨四十围，黛色参天二千尺
观者如山色沮丧，天地为之久低昂
将军得名三十载，人间又见真乘黄
英雄割据虽已矣，文采风流今尚存
美人娟娟隔秋水，濯足洞庭望八荒
人随沙岸向江村，余亦乘舟归鹿门
烟销日出不见人，欸乃一声山水绿
