平沙日未没，黯黯见临洮
熏笼玉枕无颜色，卧听南宫清漏长
劝君更尽一杯酒，西出阳关无故人
银筝夜久殷勤弄，心怯空房不忍归
良人玉勒乘骢马，侍女金盘脍鲤鱼
射杀山中白额虎，肯数邺下黄须儿
坐看红树不知远，行尽青溪不见人
