早知潮有信，嫁与弄潮儿
行人刁斗风沙暗，公主琵琶幽怨多
又向人家啄大屋，屋底达官走避胡
行人弓箭各在腰
态浓意远淑且真，肌理细腻骨肉匀
江头宫殿锁千门，细柳新蒲为谁绿
花开堪折直须折，莫待无花空折枝
