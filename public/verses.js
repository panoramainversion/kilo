export const VERSES = [...new Set(RAW.trim().split('\n').map((s) => s.trim()).filter(Boolean))];

const DECK_KEY = 'memo2-verse-deck-v2';

function shuffle(n) {
  const arr = Array.from({ length: n }, (_, i) => i);
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

function freshDeck() {
  return { pos: 0, deck: shuffle(VERSES.length) };
}

/** 取下一句；一轮抽完之前绝不重复 */
export function nextVerse() {
  let saved = null;
  try { saved = JSON.parse(localStorage.getItem(DECK_KEY) || 'null'); } catch { /* ignore */ }
  const valid = saved && Array.isArray(saved.deck)
    && saved.deck.length === VERSES.length
    && Number.isInteger(saved.pos) && saved.pos >= 0 && saved.pos < VERSES.length;
  const state = valid ? saved : freshDeck();
  const verse = VERSES[state.deck[state.pos]];
  state.pos += 1;
  try { localStorage.setItem(DECK_KEY, JSON.stringify(state)); } catch { /* ignore */ }
  return verse;
}
