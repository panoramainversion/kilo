沧江好烟月，门系钓鱼船
年年越溪女，相忆采芙蓉
忽闻歌古调，归思欲沾巾
谁能将旗鼓，一为取龙城
还将两行泪，遥寄海西头
只应守寂寞，还掩故园扉
迷津欲有问，平海夕漫漫
永怀愁不寐，松月夜窗虚
待到重阳日，还来就菊花
日夕凉风至，闻蝉但益悲
坐观垂钓者，徒有羡鱼情
羊公碑尚在，读罢泪沾襟
童颜若可驻，何惜醉流霞
乡书不可寄，秋雁又南回
何因不归去，淮上有秋山
相送情无限，沾襟比散丝
今看两楹奠，当与梦时同
寄卧郊扉久，何年致此身
云中君不见，竟夕自悲秋
那堪正飘泊，明日岁华新
未必逢矰缴，孤飞自可疑
万籁此俱寂，唯闻钟磬音
不堪盈手赠，还寝梦佳期
蕃情似此水，长愿向南流
欲祭疑君在，天涯哭此时
帝乡明日到，犹自梦渔樵
淮南一叶下，自觉洞庭波
何当重相见，樽酒慰离颜
报道山中去，归时每日斜
溪花与禅意，相对亦忘言
已似长沙傅，从今又几年
惆怅南朝事，长江独至今
茫茫江汉上，日暮欲何之
谁见汀洲上，相思愁白苹
凄凉蜀故妓，来舞魏宫前
幽映每白日，清辉照衣裳
掩泪空相向，风尘何处期
惟怜一灯影，万里眼中明
家僮扫萝径，昨与故人期
无人信高洁，谁为表予心
羁旅长堪醉，相留畏晓钟
向来吟秀句，不觉已鸣鸦
今日俸钱过十万，与君营奠复营斋
诚知此恨人人有，贫贱夫妻百事哀
惟将终夜常开眼，报答平生未展眉
强欲从君无那老，将因卧病解朝衣
朝罢须裁五色诏，佩声归向凤池头
为乘阳气行时令，不是宸游玩物华
野老与人争席罢，海鸥何事更相疑
共看明月应垂泪，一夜乡心五处同
独有凤凰池上客，阳春一曲和皆难
总为浮云能蔽日，长安不见使人愁
直道相思了无益，未妨惆怅是清狂
斑骓只系垂杨岸，何处西南任好风
蓬山此去无多路，青鸟殷勤为探看
刘郎已恨蓬山远，更隔蓬山一万重
春心莫共花争发，一寸相思一寸灰
嗟余听鼓应官去，走马兰台类转蓬
玉珰缄札何由达，万里云罗一雁飞
他年锦里经祠庙，梁父吟成恨有余
此情可待成追忆，只是当时已惘然
莫见长安行乐处，空令岁月易蹉跎
庾信平生最萧瑟，暮年诗赋动江关
最是楚宫俱泯灭，舟人指点到今疑
千载琵琶作胡语，分明怨恨曲中论
武侯祠堂常邻近，一体君臣祭祀同
运移汉祚终难复，志决身歼军务劳
已忍伶俜十年事，强移栖息一枝安
卧龙跃马终黄土，人事依依漫寂寥
即从巴峡穿巫峡，便下襄阳向洛阳
艰难苦恨繁霜鬓，潦倒新停浊酒杯
可怜后主还祠庙，日暮聊为梁甫吟
出师未捷身先死，长使英雄泪满襟
肯与邻翁相对饮，隔篱呼取尽余杯
跨马出郊时极目，不堪人事日萧条
共来百越文身地，犹自音书滞一乡
为问元戎窦车骑，何时返旆勒燕然
闻道欲来相问讯，西楼望月几回圆
少小虽非投笔吏，论功还欲请长缨
苦恨年年压金线，为他人作嫁衣裳
圣代即今多雨露，暂时分手莫踌躇
且欲近寻彭泽宰，陶然共醉菊花杯
日暮乡关何处是，烟波江上使人愁
借问路傍名利客，无如此处学长生
谁解乘舟寻范蠡，五湖烟水独忘机
茂陵不见封侯印，空向秋波哭逝川
今日龙钟人共弃，愧君犹遣慎风波
寂寂江山摇落处，怜君何事到天涯
贾谊上书忧汉室，长沙谪去古今怜
今逢四海为家日，故垒萧萧芦荻秋
旧业已随征战尽，更堪江上鼓鼙声
献赋十年犹未遇，羞将白发对华簪
遥窥正殿帘开处，袍袴宫人扫御床
何用别寻方外去，人间亦自有丹丘
忽然遭世变，数岁亲戎旃
美人清江畔，是夜越吟苦
田夫荷锄至，相见语依依
邀人傅香粉，不自着罗衣
江淮度寒食，京洛缝春衣
漾漾泛菱荇，澄澄映葭苇
四角碍白日，七层摩苍穹
洛阳访才子，江岭作流人
闻说梅花早，何如此地春
映门淮水绿，留骑主人心
明月随良掾，春潮夜夜深
大道直如发，春来佳气多
五陵贵公子，双双呜玉珂
众鸟高飞尽，孤云独去闲
相看两不厌，只有敬亭山
边地莺花少，年来未觉新
美人天上落，龙塞始应春
冷艳全欺雪，余香乍入衣
春风且莫定，吹向玉阶飞
小苑莺歌歇，长门蝶舞多
眼看春又去，翠辇不曾过
主人不相识，偶坐为林泉
莫谩愁沽酒，囊中自有钱
赵氏连城璧，由来天下传
送君还旧府，明月满前川
避人五陵去，宝剑值千金
分手脱相赠，平生一片心
君家在何处，妾住在横塘
尚有绨袍赠，应怜范叔寒
不知天下士，犹作布衣看
避贤初罢相，乐圣且衔杯
为问门前客，今朝几个来
燕赵悲歌士，相逢剧孟家
寸心言不尽，前路日将斜
咫尺愁风雨，匡庐不可登
只疑云雾窟，犹有六朝僧
林中观易罢，溪上对鸥闲
楚俗饶词客，何人最往还
何处秋风至，萧萧送雁群
朝来入庭树，孤客最先闻
山空松子落，幽人应未眠
返照入闾巷，忧来谁共语
古道少人行，秋风动禾黍
落日五湖游，烟波处处愁
浮沉千古事，谁与问东流
辇路生秋草，上林花满枝
凭高何限意，无复侍臣知
北风吹白云，万里渡河汾
心绪逢摇落，秋声不可闻
客心争日月，来往预期程
秋风不相待，先至洛阳城
白发三千丈，离愁似个长
不知明镜里，何处得秋霜
汉廷荣巧宦，云阁薄边功
可怜骢马使，白首为谁雄
仗剑行千里，微躯敢一言
曾为大梁客，不负信陵恩
强欲登高去，无人送酒来
遥怜故园菊，应傍战场开
花枝出建章，凤管发昭阳
借问承恩者，双蛾几许长
岁月人间促，烟霞此地多
殷勤竹林寺，更得几回过
沅湘流不尽，屈子怨何深
日暮秋风起，萧萧枫树林
此地别燕丹，壮士发冲冠
昔时人已没，今日水犹寒
知有前期在，难分此夜中
无将故人酒，不及石尤风
偶来松树下，高枕石头眠
山中无历日，寒尽不知年
剑阁横云峻，銮舆出狩回
翠屏千仞合，丹嶂五丁开
灌木萦旗转，仙云拂马来
乘时方在德，嗟尔勒铭才
北斗挂城边，南山倚殿前
云标金阙回，树杪玉堂悬
半岭通佳气，中峰绕瑞烟
小臣持献寿，长此戴尧天
银烛吐青烟，金尊对绮筵
离堂思琴瑟，别路绕山川
明月悬高树，长河没晓天
悠悠洛阳道，此会在何年
别业临青甸，鸣銮降紫霄
长筵鹓鹭集，仙管凤凰调
树接南山近，烟含北渚遥
承恩咸已醉，恋赏未还镳
东壁图书府，西园翰墨林
诵诗闻国政，讲易见天心
位窃和羹重，恩叨醉酒深
载歌春兴曲，情竭为知音
见说蚕丛路，崎岖不易行
山从人面起，云傍马头生
芳树笼秦栈，春流绕蜀城
升沈应已定，不必问君平
别业居幽处，到来生隐心
南山当户牖，澧水映园林
竹覆经冬雪，庭昏未夕阴
寥寥人境外，闲坐听春禽
何年顾虎头，满壁画沧州
赤日石林气，青天江海流
锡飞常近鹤，杯渡不惊鸥
似得庐山路，真随惠远游
高阁逼诸天，登临近日边
晴开万井树，愁看五陵烟
槛外低秦岭，窗中小渭川
早知清净理，常愿奉金仙
东郡趋庭日，南楼纵目初
浮云连海岱，平野入青徐
孤嶂秦碑在，荒城鲁殿余
从来多古意，临眺独踌躇
君王行出将，书记远从征
祖帐连河阙，军麾动洛城
旌旗朝朔气，笳吹夜边声
坐觉烟尘少，秋风古北平
帐殿郁崔嵬，仙游实壮哉
晓云连幕卷，夜火杂星回
谷暗千旗出，山鸣万乘来
扈从良可赋，终乏掞天才
义公习禅寂，结宇依空林
户外一峰秀，阶前众壑深
夕阳连雨足，空翠落庭阴
看取莲花净，方知不染心
世上漫相识，此翁殊不然
兴来书自圣，醉后语尤颠
白发老闲事，青云在目前
床头一壶酒，能更几回眠
浩劫因王造，平台访古游
彩云萧史驻，文字鲁恭留
宫阙通群帝，乾坤到十洲
人传有笙鹤，时过北山头
方丈浑连水，天台总映云
人间长见画，老去限空闻
范蠡舟偏小，王乔鹤不群
此生随万物，何处出尘氛
楚山不可极，归路但萧条
海色晴看雨，江声夜听潮
剑留南斗近，书寄北风遥
为报空潭橘，无媒寄洛桥
香刹夜忘归，松清古殿扉
灯明方丈室，珠系比丘衣
白日传心净，青莲喻法微
天花落不尽，处处鸟衔飞
山色远含空，苍茫泽国东
海明先见日，江白迥闻风
鸟道高原去，人烟小径通
那知旧遗逸，不在五湖中
路自中峰上，盘回出薜萝
到江吴地尽，隔岸越山多
古木丛青蔼，遥天浸白波
下方城郭近，钟磬杂笙歌
东皋薄暮望，徙倚欲何依
树树皆秋色，山山惟落晖
牧人驱犊返，猎马带禽归
相顾无相识，长歌怀采薇
金天方肃杀，白露始专征
王师非乐战，之子慎佳兵
海气侵南部，边风扫北平
莫卖卢龙塞，归邀麟阁名
香阁东山下，烟花象外幽
悬灯千嶂夕，卷幔五湖秋
画壁余鸿雁，纱窗宿斗牛
更疑天路近，梦与白云游
江城如画里，山晚望晴空
两水夹明镜，双桥落彩虹
人烟寒橘柚，秋色老梧桐
谁念北楼上，临风怀谢公
谪去君无恨，闽中我旧过
大都秋雁少，只是夜猿多
东路云山合，南天瘴疠和
自当逢雨露，行矣顺风波
凤林戈未息，鱼海路常难
候火云峰峻，悬军幕井干
风连西极动，月过北庭寒
故老思飞将，何时议筑坛
禹庙空山里，秋风落日斜
荒庭垂橘柚，古屋画龙蛇
云气生虚壁，江深走白沙
早知乘四载，疏凿控三巴
秦川朝望迥，日出正东峰
远近山河净，逶迤城阙重
秋声万户竹，寒色五陵松
有客归欤叹，凄其霜露浓
八月洞庭秋，潇湘水北流
还家万里梦，为客五更愁
不用开书帙，偏宜上酒楼
故人京洛满，何日复同游
桂楫中流望，空波两岸明
林开扬子驿，山出润州城
海尽边阴静，江寒朔吹生
更闻枫叶下，淅沥度秋声
凉风吹夜雨，萧瑟动寒林
正有高堂宴，能忘迟暮心
军中宜剑舞，塞上重笳音
不作边城将，谁知恩遇深
云淡风轻近午天，傍花随柳过前川
时人不识余心乐，将谓偷闲学少年
胜日寻芳泗水滨，无边光景一时新
等闲识得东风面，万紫千红总是春
春宵一刻值千金，花有清香月有阴
歌管楼台声细细，秋千院落夜沈沈
诗家清景在新春，绿柳才黄半未匀
若待上林花似锦，出门俱是看花人
金炉香烬漏声残，剪剪轻风阵阵寒
春色恼人眠不得，月移花影上栏杆
天街小雨润如酥，草色遥看近却无
最是一年春好处，绝胜烟柳满皇都
爆竹声中一岁除，春风送暖入屠苏
千门万户曈曈日，总把新桃换旧符
淡月疏星绕建章，仙风吹下御炉香
侍臣鹄立通明殿，一朵红云捧玉皇
律回岁晚冰霜少，春到人间草木知
便觉眼前生意满，东风吹水绿参差
阊阖千门万户开，三郎沉醉打球回
九龄已老韩休死，无复明朝谏疏来
行尽江南数十程，晓风残月入华清
朝元阁上西风急，都入长杨作雨声
酴醿香梦怯春寒，翠掩重门燕子闲
敲断玉钗红烛冷，计程应说到常山
两个黄鹂鸣翠柳，一行白鹭上青天
窗含西岭千秋雪，门泊东吴万里船
东风袅袅泛崇光，香雾空蒙月转廊
只恐夜深花睡去，故烧高烛照红妆
无花无酒过清明，兴味萧然似野僧
昨日邻家乞新火，晓窗分与读书灯
清明时节雨纷纷，路上行人欲断魂
借问酒家何处有，牧童遥指杏花村
鹅湖山下稻粱肥，豚栅鸡栖对掩扉
桑柘影斜春社散，家家扶得醉人归
千里莺啼绿映红，水村山郭酒旗风
南朝四百八十寺，多少楼台烟雨中
天上碧桃和露种，日边红杏倚云栽
芙蓉生在秋江上，不向东风怨未开
古木阴中系短篷，杖藜扶我过桥东
沾衣欲湿杏花雨，吹面不寒杨柳风
应嫌屐齿印苍苔，十扣柴扉九不开
春色满园关不住，一枝红杏出墙来
兰陵美酒郁金香，玉碗盛来琥珀光
但使主人能醉客，不知何处是他乡
呢喃燕子语梁间，底事来惊梦里闲
说与旁人浑不解，杖藜携酒看芝山
肠断春江欲尽头，杖藜徐步立芳洲
颠狂柳絮随风舞，轻薄桃花逐水流
寻得桃源好避秦，桃红又是一年春
花飞莫遣随流水，怕有渔郎来问津
紫陌红尘拂面来，无人不道看花回
玄都观里桃千树，尽是刘郎去后栽
百亩庭中半是苔，桃花净尽菜花开
种桃道士归何处，前度刘郎今又来
重重叠叠上瑶台，几度呼童扫不开
刚被太阳收拾去，却教明月送将来
北山输绿涨横陂，直堑回塘滟滟时
细数落花因坐久，缓寻芳草得归迟
花开红树乱莺啼，草长平湖白鹭飞
风日晴和人意好，夕阳箫鼓几船归
糁径杨花铺白毡，点溪荷叶叠青钱
笋根稚子无人见，沙上凫雏傍母眠
雨前初见花间蕊，雨后全无叶底花
蜂蝶纷纷过墙去，却疑春色在邻家
