山光悦鸟性，潭影空人心
灭烛怜光满，披衣觉露滋
大汉无兵阻，穷边有客游
无人收废帐，归马识残旗
树色随山迥，河声入海遥
高树晓还密，远山晴更多
江上几人在，天涯孤棹还
扣门无犬吠，欲去问西家
过雨看松色，随山到水源
岭猿同旦暮，江柳共风烟
夕阳依旧垒，寒磬满空林
独立三边静，轻生一剑知
长江一帆远，落日五湖春
得相能开国，生儿不象贤
闲门向山路，深柳读书堂
少孤为客早，多难识君迟
水月通禅寂，鱼龙听梵声
闲鹭栖常早，秋花落更迟
露重飞难进，风多响易沉
风枝惊暗鹊，露草覆寒蛩
节候看应晚，心期卧亦赊
野蔬充膳甘长藿，落叶添薪仰古槐
尚想旧情怜婢仆，也曾因梦送钱财
