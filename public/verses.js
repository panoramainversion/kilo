竹喧归浣女，莲动下渔舟
荒城临古渡，落日满秋山
海日生残夜，江春入旧年
孤灯寒照雨，深竹暗浮烟
以我独沉久，愧君相见频
晓月过残垒，繁星宿故关
远芳侵古道，晴翠接荒城
江静潮初落，林昏瘴不开
白发悲花落，青云羡鸟飞
客心洗流水，余响入霜钟
余亦能高咏，斯人不可闻
醉月频中圣，迷花不事君
月下飞天镜，云生结海楼
浮云游子意，落日故人情
别来沧海事，语罢暮天钟
北斗兼春远，南陵寓使迟
独敲初夜磬，闲倚一枝藤
薄宦梗犹泛，故园芜已平
新知遭薄俗，旧好隔良缘
肠断未忍扫，眼穿仍欲归
亲朋无一字，老病有孤舟
列郡讴歌惜，三朝出入荣
对棋陪谢傅，把剑觅徐君
名岂文章着，官应老病休
近得归京邑，移官岂至尊
有弟皆分散，无家问死生
文章憎命达，魑魅喜人过
香雾云鬟湿，清辉玉臂寒
烽火连三月，家书抵万金
不寝听金钥，因风想玉珂
远梦归侵晓，家书到隔年
风暖鸟声碎，日高花影重
淑气催黄鸟，晴光转绿苹
少妇今春意，良人昨夜情
建德非吾土，维扬忆旧游
