松际露微月，清光犹为君
侧见双翠鸟，巢在三珠树
欣欣此生意，自尔为佳节
持此谢高鸟，因之传远情
岂伊地气暖，自有岁寒心
晚风吹行舟，花路入溪口
夏水欲满君山青
杨家有女初长成，养在深闺人未识
主人下马客在船，举酒欲饮无管弦
随风满地石乱走
羽书昨夜过渠黎，单于已在金山西
忽如一夜春风来，千树万树梨花开
乱我心者，今日之日多烦忧
手持绿玉杖，朝别黄鹤楼
越人语天姥，云霞明灭或可睹
金陵子弟来相送，欲行不行各尽觞
