借问汉宫谁得似，可怜飞燕倚新妆
停杯投箸不能食，拔剑四顾心茫然
羞逐长安社中儿，赤鸡白雉赌梨栗
含光混世贵无名，何用孤高比云月
奔流到海不复回
却下水晶帘，玲珑望秋月
络纬秋啼金井阑，微霜凄凄簟色寒
赵瑟初停凤凰柱，蜀琴欲奏鸳鸯弦
郎骑竹马来，绕床弄青梅
蜀道之难，难于上青天
素手青条上，红妆白日鲜
五月西施采，人看隘若耶
秋风吹不尽，总是玉关情
素手抽针冷，那堪把剪刀
